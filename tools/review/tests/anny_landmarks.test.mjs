// 브라우저 투영과 가시 표면 선택의 기하학 검증. WebGL 렌더 자체는 브라우저에서 검수한다.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const currentVmContext=vm.createContext({window:{},AnnyMeshPreview:class {}});
vm.runInContext(fs.readFileSync(new URL('../ui/anny/anny-landmarks.js',import.meta.url),'utf8')+'\nwindow.LandmarkPreviewClass=AnnyLandmarkPreview;',currentVmContext);
const currentPreviewObject=Object.create(currentVmContext.window.LandmarkPreviewClass.prototype);
Object.assign(currentPreviewObject,{previewCenterValues:[0,0,0],previewYawRadians:0,previewPitchRadians:0,previewZoomFactor:1,previewHeightValue:1.7,previewCanvasElement:{clientWidth:200,clientHeight:200}});
assert.deepEqual(Array.from(currentPreviewObject.projectCandidatePoint([.5,-.2,.5])),[150,50,-.2]);
currentPreviewObject.currentSourceRecord={vertices:[[-.5,-.2,-.5],[.5,-.2,-.5],[0,-.2,.5],[-.5,.2,-.5],[.5,.2,-.5],[0,.2,.5]],faces:[[3,4,5],[0,1,2]]};
assert.equal(currentPreviewObject.pickVisibleVertex([100,60])[1],-.2,'가까운 면을 선택해야 함');
assert.equal(currentPreviewObject.pickVisibleVertex([0,0]),null,'빈 공간은 선택하지 않음');
currentPreviewObject.previewYawRadians=Math.PI;
assert.equal(currentPreviewObject.pickVisibleVertex([100,60])[1],.2,'후면에서 반대쪽 면 선택');
console.log('ANNY 투영·가시 삼각형·후면 선택 검사 통과');
let currentRedrawCount=0;
currentVmContext.window.currentAnnyLandmarkViewer={currentPickedPoint:[1,2,3],drawPreviewMesh(){currentRedrawCount+=1;}};
currentVmContext.window.updateLandmarkViewer(JSON.stringify({draft:{points:{example:{position:[3,2,1]}}},review:{axes:[]}}));
assert.deepEqual(Array.from(currentVmContext.window.currentAnnyLandmarkViewer.currentPickedPoint),[1,2,3],'다른 후보 갱신은 아직 반영하지 않은 선택을 유지');
currentVmContext.window.updateLandmarkViewer(JSON.stringify({draft:{points:{example:{position:[1,2,3]}}},review:{axes:[]}}));
assert.equal(currentVmContext.window.currentAnnyLandmarkViewer.currentPickedPoint,null,'반영된 선택의 미반영 마커를 해제');
assert.equal(currentRedrawCount,2,'선택 해제 후에도 후보 마커를 다시 그림');
const currentPointerHandlers=new Map();
const currentPointerCanvas={addEventListener(currentEventName,currentEventHandler){currentPointerHandlers.set(currentEventName,currentEventHandler);},getBoundingClientRect(){return {left:0,top:0};}};
currentVmContext.window.LandmarkPreviewClass.prototype.loadPreviewMeshPayload=()=>{};
const currentPointerPreview=new currentVmContext.window.LandmarkPreviewClass(currentPointerCanvas,null,{vertices:[],faces:[]});
let currentPickCount=0;
currentPointerPreview.pickVisibleVertex=()=>{currentPickCount+=1;return [1,2,3];};
currentPointerPreview.drawPreviewMesh=()=>{};
const dispatchPointerEvent=(currentEventName,currentPixelValue)=>currentPointerHandlers.get(currentEventName)?.({pointerId:1,clientX:currentPixelValue,clientY:10});
dispatchPointerEvent('pointerdown',10);
dispatchPointerEvent('pointermove',30);
dispatchPointerEvent('pointermove',10);
dispatchPointerEvent('pointerup',10);
assert.equal(currentPickCount,0,'드래그 후 시작 위치 복귀는 선택하지 않음');
dispatchPointerEvent('pointerdown',10);
dispatchPointerEvent('pointercancel',10);
dispatchPointerEvent('pointerup',10);
assert.equal(currentPickCount,0,'취소된 포인터는 선택하지 않음');
dispatchPointerEvent('pointerdown',10);
dispatchPointerEvent('pointerup',11);
assert.equal(currentPickCount,1,'작은 흔들림의 클릭은 선택');
dispatchPointerEvent('pointerup',11);
assert.equal(currentPickCount,1,'이미 종료된 포인터는 재선택하지 않음');
dispatchPointerEvent('pointerdown',10);
dispatchPointerEvent('lostpointercapture',10);
dispatchPointerEvent('pointerup',10);
assert.equal(currentPickCount,1,'포인터 캡처 해제 후 선택하지 않음');
